$tsvPath = $argv[1] ?? '/tmp/inventory.tsv';
$outPath = $argv[2] ?? 'documentation/frontend/AH77_SOURCE_INVENTORY.md';

$lines = file($tsvPath, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
if ($lines === false || count($lines) < 2) {
    fwrite(STDERR, "Empty or unreadable inventory: {$tsvPath}\n");
    exit(1);
}

$headers = explode("\t", array_shift($lines));
$rows = [];
foreach ($lines as $line) {
    $cells = explode("\t", $line);
    if (count($cells) !== count($headers)) {
        continue;
    }
    $rows[] = array_combine($headers, $cells);
}

function classify(array $row): string
{
    $ext = $row['ext'];
    $mime = $row['mime'];
    $path = $row['path'];

    if (str_contains($path, '/cdnjs.cloudflare.com/') || str_contains($path, '/cdn.jsdelivr.net/')) {
        return 'Dependency';
    }
    if ($ext === 'html') {
        return 'HTML';
    }
    if ($ext === 'css') {
        return 'CSS';
    }
    if ($ext === 'js') {
        return 'JavaScript';
    }
    if ($ext === 'svg') {
        return 'Vector';
    }
    if (in_array($ext, ['avif', 'webp'], true)) {
        return 'Modern image';
    }
    if (in_array($ext, ['png', 'jpg', 'jpeg'], true)) {
        return 'Image';
    }
    if ($ext === 'gif' || str_starts_with($mime, 'video/')) {
        return 'Animation';
    }
    if (in_array($ext, ['woff', 'woff2', 'ttf', 'otf'], true)) {
        return 'Font';
    }
    if ($ext === 'json') {
        return 'Manifest';
    }
    return 'Unknown';
}

function humanBytes(int $bytes): string
{
    if ($bytes >= 1048576) {
        return number_format($bytes / 1048576, 2) . ' MB';
    }
    if ($bytes >= 1024) {
        return number_format($bytes / 1024, 1) . ' KB';
    }
    return $bytes . ' B';
}

